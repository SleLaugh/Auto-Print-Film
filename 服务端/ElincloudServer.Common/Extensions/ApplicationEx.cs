        public static int GetRemainDays(string _licence, string _cpuid)
        {
            try
            {
                int version = 1;
                string decriptKey = ElincloudServer.Common.Utils.StringUtil.Decrypt(_licence, _cpuid);
                if (decriptKey != string.Empty)
                {
                    string[] keys = decriptKey.Split('|');
                    if (keys != null && keys.Length == 3 && keys[1] == AppName + version)
                    {
                        int allowDays = Convert.ToInt32(keys[2]);
                        if (allowDays > 0)//只允许使用allowDays天
                        {
                            DateTime currentDate = DateTime.Now;
                            DateTime registDate = DateTime.ParseExact(keys[0], "yyyyMMddHH", System.Globalization.CultureInfo.CurrentCulture);
                            if (currentDate >= registDate)
                            {
                                int costDays = (int)(currentDate - registDate).TotalDays;
                                int remainDays = allowDays - costDays;
                                if (remainDays >= 0)
                                {
                                    return remainDays;
                                }
                            }
                        }
                        else if (allowDays == 0)//不限制
                        {
                            return 9999;
                        }
                    }
                }
                return -1;
            }
            catch (Exception ex)
            {
                ElincloudServer.Common.Utils.LogUtil.RecordErrorLog("获取授权时长异常!", ex);
                return -1;
            }
        }

